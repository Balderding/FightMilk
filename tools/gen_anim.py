def pts(lst):
    return "[" + ", ".join(f"Offset({x}, {y})" for x, y in lst) + "]"


def check(name, b, a):
    assert len(b["body"]) == len(a[1]), (name, "lines")
    for i, (lb, la) in enumerate(zip(b["body"], a[1])):
        assert len(lb) == len(la), (name, "points in line", i)
    assert len(b["hands"]) == len(a[2]), (name, "hands")


lines = ["// GENERATED by tools/gen_anim.py - do not edit by hand.", "import 'dart:ui';", "", "import 'pose.dart';", "", "const poseData = <String, PosePair>{"]
for name, b in P.items():
    a = A[name]
    check(name, b, a)
    hb = b["head"]
    props = "[" + ", ".join(pts(pr) for pr in b["prop"]) + "]"
    lines.append(f"  '{name}': PosePair(")
    lines.append(f"    a: Pose(head: Offset({a[0][0]}, {a[0][1]}), body: [{', '.join(pts(l) for l in a[1])}], hands: {pts(a[2])}),")
    lines.append(f"    b: Pose(head: Offset({hb[0]}, {hb[1]}), body: [{', '.join(pts(l) for l in b['body'])}], hands: {pts(b['hands'])}),")
    lines.append(f"    props: {props},")
    lines.append(f"    kind: '{b['kind']}',")
    lines.append(f"    liftAB: {'true' if a[3] == 'AB' else 'false'},")
    lines.append("  ),")
lines.append("};")
